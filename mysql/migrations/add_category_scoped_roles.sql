-- Category-scoped roles (Phase 1).
--
-- Adds two roles that mirror the location-scoped pair (inventory_location_manager /
-- inventory_location_assistant, levels 6/7) but constrain a staff member to the
-- item CATEGORIES assigned to them instead of locations:
--   category_manager   (level 8): inventory(CRUD), scoped to assigned categories.
--   category_assistant (level 9): inventory(RU),   scoped to assigned categories.
--
-- Like the location-scoped roles, these are NOT in FULL_INVENTORY_ROLES ({0,1,4})
-- and are constrained by rows in staff_category_access (fail-closed: no rows = no
-- inventory visible, enforced in the controllers — Phase 4).
--
-- Idempotent: safe to re-run (CREATE TABLE IF NOT EXISTS + INSERT IGNORE + guarded
-- index creation). This migration MUST be applied before deploying the backend
-- change to mysql/helpers/staffAccess.js, which LEFT JOINs staff_category_access.

-- ─── staff_category_access ─────────────────────────────────────────────────────
-- Mirrors staff_location_access: char(36) UUID ids generated by the application
-- layer (see mysql/scripts/migrate-roles.js), category_id is the int PK of
-- company_item_categories. can_* flags reserved for per-action granularity.
CREATE TABLE IF NOT EXISTS staff_category_access (
  id               CHAR(36)   NOT NULL,
  company_staff_id CHAR(36)   NOT NULL,
  category_id      INT        NOT NULL,
  can_create       TINYINT(1) DEFAULT 0,
  can_update       TINYINT(1) DEFAULT 0,
  can_delete       TINYINT(1) DEFAULT 0,
  PRIMARY KEY (id),
  INDEX idx_sca_company_staff_id (company_staff_id),
  INDEX idx_sca_category_id (category_id),
  UNIQUE KEY uq_sca_staff_category (company_staff_id, category_id)
);

-- ─── ROLES ─────────────────────────────────────────────────────────────────────
INSERT IGNORE INTO roles (role_level, role_type, label) VALUES
  (8, 'category_manager',   'Category Manager'),
  (9, 'category_assistant', 'Category Assistant');

-- ─── ROLE_PERMISSIONS ────────────────────────────────────────────────────────
-- category_manager (level 8): inventory CRUD, constrained by category scope.
INSERT IGNORE INTO role_permissions
  SELECT r.id, p.id FROM roles r, permissions p
  WHERE r.role_type = 'category_manager'
    AND p.resource = 'inventory';

-- category_assistant (level 9): inventory read/update only, constrained by scope.
INSERT IGNORE INTO role_permissions
  SELECT r.id, p.id FROM roles r, permissions p
  WHERE r.role_type = 'category_assistant'
    AND p.resource = 'inventory'
    AND p.action IN ('read','update');

-- ─── item_inv(category_name) index ─────────────────────────────────────────────
-- The scope filter is `category_name IN (...)` on item_inv (no category_id FK on
-- that table). Add a supporting index only if it does not already exist.
SET @dbname = DATABASE();
SET @tablename = "item_inv";
SET @indexname = "idx_item_inv_category_name";
SET @createIndexSql = (SELECT IF(
  (
    SELECT COUNT(*) FROM INFORMATION_SCHEMA.STATISTICS
    WHERE table_schema = @dbname
      AND table_name = @tablename
      AND index_name = @indexname
  ) > 0,
  "SELECT 1",
  "CREATE INDEX idx_item_inv_category_name ON item_inv(category_name)"
));
PREPARE createIndexIfNotExists FROM @createIndexSql;
EXECUTE createIndexIfNotExists;
DEALLOCATE PREPARE createIndexIfNotExists;
